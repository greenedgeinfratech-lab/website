// Helper methods
export function getBlogs(page = 1, limit = 6) {
  const start = (page - 1) * limit;
  const items = store.blogs.slice(start, start + limit);
  return {
    items,
    total: store.blogs.length,
    totalPages: Math.ceil(store.blogs.length / limit),
    page
  };
}

export function getBlogById(id) {
  return store.blogs.find(b => b.id === Number(id));
}

export function addBlog(blog) {
  const newBlog = {
    id: store.blogs.length > 0 ? Math.max(...store.blogs.map(b => b.id)) + 1 : 1,
    ...blog,
    created_at: new Date().toISOString().replace('T', ' ').substring(0, 19)
  };
  store.blogs.unshift(newBlog);
  return newBlog;
}

export function deleteBlog(id) {
  const initialLen = store.blogs.length;
  store.blogs = store.blogs.filter(b => b.id !== Number(id));
  return store.blogs.length < initialLen;
}

export function getServices() {
  return store.services.filter(s => s.is_active === 1);
}

export function getServiceById(id) {
  return store.services.find(s => s.id === Number(id) && s.is_active === 1);
}

export function getProducts() {
  return store.products.filter(p => p.is_active === 1);
}

export function getProductBySlugOrId(identifier) {
  return store.products.find(p => (p.slug === identifier || String(p.id) === String(identifier)) && p.is_active === 1);
}

